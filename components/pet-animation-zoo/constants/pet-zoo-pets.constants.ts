export type PetZooPetType = (typeof PET_ZOO_PET_TYPES)[number];

/** Walking speeds in px per second. Each pet also gets a random factor, so two of the same kind never move in sync. */
export const PET_ZOO_SPEED = {
  still: 0,
  verySlow: 9,
  slow: 16,
  normal: 24,
  fast: 32,
  veryFast: 40,
} as const;

const BASIC_ANIMATIONS: readonly PetZooAnimation[] = ['idle', 'walk', 'walk_fast', 'run', 'swipe', 'with_ball'];
const ANIMATIONS_WITH_LIE: readonly PetZooAnimation[] = [...BASIC_ANIMATIONS, 'lie'];
const ANIMATIONS_WITH_STAND: readonly PetZooAnimation[] = [...BASIC_ANIMATIONS, 'stand'];

function colors(...values: string[]): readonly PetZooPetColorDefinition[] {
  return values.map((value: string) => {
    return { value, label: PET_ZOO_COLOR_LABELS[value] ?? value };
  });
}

